// Turns the TBCrushCalc app's game data into Lua files for the addon: node tools/export_data.mjs <app repo>
// Everything comes from the app (its generated JSON and the hand-written tables in src/data.ts), so the
// addon and the app always work from the same items, gems, enchants, consumables, bosses, talents and buffs.
import * as esbuild from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';

const here = path.dirname(new URL(import.meta.url).pathname);
const root = path.dirname(here);
const app = path.resolve(process.argv[2] || '../bigcrazyworld');
const out = path.join(root, 'TBCrushCalc', 'Data');
const bundle = path.join(root, 'build', 'app.cjs');

export async function buildApp() {
  await esbuild.build({
    entryPoints: [path.join(here, 'app_entry.ts')], bundle: true, platform: 'node', format: 'cjs', target: ['node18'],
    outfile: bundle, logLevel: 'warning', alias: { '@app': path.join(app, 'src') },
    define: { BUILD_TIME: '"export"', APP_VERSION: '"export"' },
  });
  const require = createRequire(import.meta.url);
  const m = require(bundle);
  await m.D.loadData(async n => JSON.parse(fs.readFileSync(path.join(app, 'web', 'data', n + '.json'), 'utf8')));
  return m;
}

// ------------------------------------------------------------------ Lua writer
const IDENT = /^[A-Za-z_][A-Za-z0-9_]*$/;
const RESERVED = new Set(['and', 'break', 'do', 'else', 'elseif', 'end', 'false', 'for', 'function', 'if', 'in', 'local', 'nil', 'not', 'or', 'repeat', 'return', 'then', 'true', 'until', 'while']);
function str(s) {
  return '"' + s.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n').replace(/\r/g, '\\r') + '"';
}
export function lua(v) {
  if (v === null || v === undefined) return 'nil';
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  if (typeof v === 'number') {
    if (!Number.isFinite(v)) throw new Error('bad number ' + v);
    return String(v);
  }
  if (typeof v === 'string') return str(v);
  if (Array.isArray(v)) return '{' + v.map(lua).join(',') + '}';
  if (v instanceof Map) v = Object.fromEntries(v);
  const parts = [];
  for (const k of Object.keys(v)) {
    if (v[k] === undefined) continue;
    const key = IDENT.test(k) && !RESERVED.has(k) ? k : /^-?\d+$/.test(k) ? `[${k}]` : `[${str(k)}]`;
    parts.push(`${key}=${lua(v[k])}`);
  }
  return '{' + parts.join(',') + '}';
}

function write(name, comment, body) {
  fs.writeFileSync(path.join(out, name), `-- ${comment}\n-- Generated by tools/export_data.mjs from the TBCrushCalc app. Do not edit by hand.\nlocal _, T = ...\n${body}\n`);
}

async function main() {
  const { D } = await buildApp();
  fs.mkdirSync(out, { recursive: true });
  for (const f of fs.readdirSync(out)) if (f.endsWith('.lua')) fs.unlinkSync(path.join(out, f));

  // items: in chunks (one Lua function can only hold so many constants); the game draws item tooltips itself
  const items = D.ITEMS.map(it => { const c = { ...it }; delete c.tt; return c; });
  const CHUNK = 1200;
  const itemFiles = [];
  for (let i = 0; i < items.length; i += CHUNK) {
    const n = String(itemFiles.length + 1).padStart(2, '0');
    const name = `Items${n}.lua`;
    write(name, `Items ${i + 1}-${Math.min(items.length, i + CHUNK)} of ${items.length}`,
      `local I = T.ITEMS\n` + items.slice(i, i + CHUNK).map(it => `I[#I+1]=${lua(it)}`).join('\n'));
    itemFiles.push(name);
  }
  write('Sets.lua', 'Item sets: pieces and bonuses', `T.SETS = ${lua(D.SETS)}`);
  write('Gems.lua', 'Every TBC gem', `T.GEMS = {\n${D.GEMS.map(g => lua(g)).join(',\n')}\n}`);
  write('Enchants.lua', 'Every TBC enchant, armor kit, glyph and inscription', `T.ENCHANTS = {\n${D.ENCHANTS.map(e => lua(e)).join(',\n')}\n}\nT.ENCHANT_ALIAS = ${lua(D.ENCHANT_ALIAS)}`);
  write('Consumables.lua', 'Flasks, elixirs, food, scrolls and potions', `T.CONSUMABLES = {\n${D.CONSUMABLES.map(c => lua(c)).join(',\n')}\n}`);
  write('Bosses.lua', 'TBC raid bosses', `T.BOSSES = {\n${D.BOSSES.map(b => lua(b)).join(',\n')}\n}`);
  write('Talents.lua', 'Talent trees for warriors, paladins and druids', `T.TALENTS = ${lua(D.TALENTS)}`);
  write('Static.lua', 'Base stats, buffs, debuffs, world buffs, abilities, classes, races, slots and names', [
    `T.BASES = ${lua(D.BASES)}`,
    `T.RAID_BUFFS = ${lua(D.RAID_BUFFS)}`,
    `T.DEBUFFS = ${lua(D.DEBUFFS)}`,
    `T.WORLD_BUFFS = ${lua(D.WORLD_BUFFS)}`,
    `T.ABILITIES = ${lua(D.ABILITIES)}`,
    `T.CLASSES = ${lua(D.CLASSES)}`,
    `T.RACE_NAMES = ${lua(D.RACE_NAMES)}`,
    `T.RACE_ICON = ${lua(D.RACE_ICON)}`,
    `T.SLOTS = ${lua(D.SLOTS)}`,
    `T.BEST_ARMOR = ${lua(D.BEST_ARMOR)}`,
    `T.WEAPONS = ${lua(D.WEAPONS)}`,
    `T.RANGED = ${lua(D.RANGED)}`,
    `T.ARMOR = ${lua(D.ARMOR)}`,
    `T.QUALITY_COLOR = ${lua(D.QUALITY_COLOR)}`,
    `T.STAT_NAMES = ${lua(D.STAT_NAMES)}`,
  ].join('\n'));
  fs.writeFileSync(path.join(out, 'Data.xml'), `<Ui xmlns="http://www.blizzard.com/wow/ui/">\n${
    [...itemFiles, 'Sets.lua', 'Gems.lua', 'Enchants.lua', 'Consumables.lua', 'Bosses.lua', 'Talents.lua', 'Static.lua'].map(f => `  <Script file="${f}"/>`).join('\n')}\n</Ui>\n`);
  const size = fs.readdirSync(out).reduce((n, f) => n + fs.statSync(path.join(out, f)).size, 0);
  console.log(`items ${items.length} in ${itemFiles.length} files, gems ${D.GEMS.length}, enchants ${D.ENCHANTS.length}, consumables ${D.CONSUMABLES.length}, bosses ${D.BOSSES.length}; ${(size / 1024 / 1024).toFixed(2)} MB`);
}
if (process.argv[1] && process.argv[1].endsWith('export_data.mjs')) main();
